// Public v5 authoring -> pinned-native -> qualified sampled observables.
import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createRequire} from 'node:module';
import {prepareScene} from '../src/authoring.js';
import {evaluateDocument} from '../scripts/author-scene.mjs';
import {evaluateObservables} from '../src/observables.js';
import {parseSave,serializeSave} from '../src/contract.js';
import {analyzeMirrorBackedSlab} from '../src/mirror-backed-slab-displacement.js';
const core=createRequire(import.meta.url)('../dist/test-core.cjs');
const fixture=JSON.parse(readFileSync(new URL('../examples/jee-j08-mirror-backed-slab-native-v1.json',import.meta.url),'utf8'));
const standalone=JSON.parse(readFileSync(new URL('../examples/jee-j08-mirror-backed-slab-synthetic-air-v1.json',import.meta.url),'utf8'));
const near=(x,y,t=1e-7)=>assert.ok(Number.isFinite(x)&&Math.abs(x-y)<=t,String(x)+' differs from '+String(y));
const run=async r=>{
 const d=prepareScene(r.physical).document;
 const evaluated=evaluateDocument(d,core,r.requests);
 const results=(await evaluateObservables(d,r.requests,evaluated.summary)).results;
 return {d,evaluated,results,byId:Object.fromEntries(results.map(x=>[x.id,x]))};
};
test('originally supported v5 scene authoring traces actual entry-Mirror-exit, with qualified native counts',async()=>{
 const input=structuredClone(fixture),before=structuredClone(input);
 const {d,evaluated,results,byId}=await run(input);
 assert.deepEqual(input,before);
 assert.equal(d.schemaVersion,5);
 assert.equal(d.adapterVersion,5);
 assert.equal(d.physics.model,'planar-media-tracing');
 assert.deepEqual(core.compile(d).native.objs.map(x=>x.type),['SingleRay','PlaneGlass','Mirror','Detector']);
 assert.deepEqual(parseSave(serializeSave(d)),d);
 assert.equal(evaluated.summary.executionPassed,true);
 assert.equal(evaluated.summary.native.status,'completed');
 assert.equal(evaluated.summary.native.truncation,0);
 assert.equal(evaluated.summary.native.undefinedBehavior,0);
 assert.ok(results.every(r=>r.status==='qualified'),'Explicit Fresnel-off profile should be a completed qualified approximation');
 assert.equal(byId['glass-interactions'].value,2);
 assert.equal(byId['mirror-reflections'].value,1);
 assert.equal(byId.crossings.value,2);
 assert.equal(byId['sample-hit-positions'].value.length,2);
 assert.ok(byId['sample-hit-positions'].warnings.some(x=>x.includes('transmitted-only')));
 assert.equal(byId['sample-hit-positions'].method,'native-hit-event-observation');
 assert.equal(byId['first-entry'].value.incidentIndex,1);
 assert.equal(byId['first-entry'].value.destinationIndex,1.8);
 near(byId['first-entry'].value.incidentAngleDeg,60);
});
test('sampled external detector hit spacing is NOT mistaken for the front-face surface displacement',async()=>{
 const {byId}=await run(fixture);
 const events=byId['sample-hit-positions'].value;
 const first=events[0],last=events[1],i=Math.PI/3;
 const predicted=analyzeMirrorBackedSlab(standalone);
 assert.equal(predicted.status,'conditional');
 assert.ok(first.pointMm&&last.pointMm);
 near(first.pointMm.x,-10);
 near(last.pointMm.x,-10);
 near(first.pointMm.y,-10*Math.tan(i),1e-7);
 near(last.pointMm.y,predicted.value.entranceToExitSeparationMm+10*Math.tan(i),1e-7);
 const measuredGap=last.pointMm.y-first.pointMm.y;
 near(measuredGap,predicted.value.entranceToExitSeparationMm+20*Math.tan(i),1e-7);
 assert.ok(Math.abs(measuredGap-predicted.value.entranceToExitSeparationMm)>30);
 assert.ok(first.incomingUnit.x>0&&last.incomingUnit.x<0);
 assert.equal(byId['sample-hit-positions'].limitation.includes('not one ray path'),true);
});
test('same supported v5 public authoring fails closed on missing exterior, mirror removal or stale changes',async()=>{
 const base=structuredClone(fixture);
 const noGlassExterior=structuredClone(base);
 delete noGlassExterior.physical.components.find(x=>x.id==='I').parameters.negativeIndex;
 assert.throws(()=>prepareScene(noGlassExterior.physical));
 const noMirror=structuredClone(base);
 noMirror.physical.components=noMirror.physical.components.filter(x=>x.id!=='M');
 noMirror.requests=noMirror.requests.filter(x=>x.componentId!=='M');
 const r=await run(noMirror);
 assert.equal(r.evaluated.summary.native.status,'completed');
 assert.equal(r.byId['glass-interactions'].value,1);
 assert.equal(r.byId.crossings.value,1);
 const good=await run(base);
 const changed=structuredClone(good.d);
 changed.physics.components.find(x=>x.id==='I').parameters.positiveIndex=1.5;
 const stale=(await evaluateObservables(changed,base.requests,good.evaluated.summary)).results;
 assert.ok(stale.every(x=>x.status==='suppressed'&&x.value===null));
});
